"""Scorecard PNG — dither-flavoured report card rendered with PIL.

1200x630 (OG-card sized) so it screenshots and shares well. Matches the
DataBard dark palette; colours follow the one score->tone rule (80/50).
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).parent
FONT_PATH = HERE / "assets" / "SpaceGrotesk.ttf"

BG = (18, 14, 28)
SURFACE = (32, 24, 48)
TEXT = (240, 238, 248)
MUTED = (150, 144, 170)
ACCENT = (139, 92, 246)
TONE = {
    "healthy": (91, 245, 140),
    "at-risk": (245, 200, 66),
    "critical": (245, 91, 91),
}
VERDICT = {"healthy": "Healthy", "at-risk": "At risk", "critical": "Critical"}


def _font(size, weight=400):
    f = ImageFont.truetype(str(FONT_PATH), size)
    try:
        f.set_variation_by_axes([weight])
    except Exception:
        pass
    return f


def render_scorecard(schema_name, insights, quote, out_path, table_count):
    W, H = 1200, 630
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)
    score = insights["healthScore"]
    tone = TONE[insights["healthLabel"]]

    # dither strip — two rows of alternating cells as a brand mark
    for x in range(0, W, 8):
        for y in range(0, 16, 8):
            if ((x // 8) + (y // 8)) % 2 == 0:
                d.rectangle([x, y, x + 7, y + 7], fill=ACCENT if (x // 8) % 5 else SURFACE)

    d.text((56, 56), "DATABARD x BEAM", font=_font(22, 500), fill=MUTED)
    d.text((56, 92), "DATA HEALTH SCORECARD", font=_font(16, 400), fill=MUTED)

    # Score block
    d.text((56, 170), schema_name[:40], font=_font(44, 700), fill=TEXT)
    d.text((56, 236), f"{table_count} tables  -  scored by the production DataBard rubric",
           font=_font(20, 400), fill=MUTED)

    d.text((56, 300), str(score), font=_font(150, 700), fill=tone)
    sw = d.textlength(str(score), font=_font(150, 700))
    d.text((56 + sw + 16, 396), "/ 100", font=_font(28, 400), fill=MUTED)
    # verdict pill
    px, py = 56 + sw + 120, 386
    label = VERDICT[insights["healthLabel"]].upper()
    lw = d.textlength(label, font=_font(22, 700))
    d.rounded_rectangle([px, py, px + lw + 36, py + 44], radius=8, outline=tone, width=2)
    d.text((px + 18, py + 9), label, font=_font(22, 700), fill=tone)

    # Findings column
    fx = 620
    findings = []
    if insights["failingTests"]:
        findings.append(f"{insights['failingTests']} failing quality tests")
    if insights["untestedTables"]:
        findings.append(f"{len(insights['untestedTables'])} tables with zero tests "
                        f"({insights['testCoverage']}% coverage)")
    if insights["undocumentedTables"]:
        findings.append(f"{len(insights['undocumentedTables'])} undocumented tables")
    if insights["piiTables"]:
        n = sum(len(p["columns"]) for p in insights["piiTables"])
        findings.append(f"{n} PII columns across {len(insights['piiTables'])} tables")
    if insights["ownerlessTables"]:
        findings.append(f"{len(insights['ownerlessTables'])} tables have no owner")
    if not findings:
        findings.append("No structural defects detected")

    d.text((fx, 170), "FINDINGS", font=_font(18, 700), fill=MUTED)
    y = 208
    for f_ in findings[:5]:
        d.rectangle([fx, y + 8, fx + 10, y + 18], fill=tone)
        d.text((fx + 24, y), f_[:56], font=_font(22, 400), fill=TEXT)
        y += 40

    # Quote
    if quote:
        q = quote if len(quote) <= 180 else quote[:177] + "..."
        # crude wrap
        words, lines, cur = q.split(" "), [], ""
        for w in words:
            if d.textlength(cur + " " + w, font=_font(19, 400)) > 1060:
                lines.append(cur)
                cur = w
            else:
                cur = (cur + " " + w).strip()
        if cur:
            lines.append(cur)
        qy = 470
        for ln in lines[:3]:
            d.text((56, qy), '"' + ln + '"' if ln is lines[0] else ln,
                   font=_font(19, 400), fill=MUTED)
            qy += 28

    d.rectangle([0, H - 6, W, H], fill=ACCENT)
    d.text((56, H - 44), "generated by Beam 1.0 501B  -  databard.persidian.com/benchmarks/beam",
           font=_font(16, 400), fill=MUTED)

    img.save(out_path)
    return out_path

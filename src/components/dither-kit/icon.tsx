export type PixelIconName = keyof typeof GLYPHS

export type PixelIconProps = {
  name: PixelIconName
  /** Square size in px. */
  size?: number
  className?: string
  title?: string
}

/** One <rect> per horizontal run of lit cells — 8 rows stay a handful of nodes. */
function cells(rows: readonly string[]) {
  const rects: Array<{ x: number; y: number; w: number }> = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== "1") {
        x++
        continue
      }
      let end = x
      while (end < row.length && row[end] === "1") end++
      rects.push({ x, y, w: end - x })
      x = end
    }
  })
  return rects
}

export function PixelIcon({ name, size = 16, className, title }: PixelIconProps) {
  const rects = cells(GLYPHS[name])
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 8 8"
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden={title ? undefined : true}
      role={title ? "img" : undefined}
      className={cn("shrink-0", className)}
    >
      {title && <title>{title}</title>}
      {rects.map((r) => (
        <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1} />
      ))}
    </svg>
  )
}
